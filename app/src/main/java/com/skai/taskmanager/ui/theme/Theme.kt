/**
 * App-wide Material 3 theme with dark-mode support and Material You dynamic color on
 * Android 12+ (falls back to the brand palette on older devices).
 */
@Composable
fun TaskManagerTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit
) {
    val context = LocalContext.current
    val appearance by AppearancePreferences.state.collectAsStateWithLifecycle()
    val studio = appearance.app == AppStyle.STUDIO
    val colorScheme = when {
        studio -> if (darkTheme) StudioDark else StudioLight
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        darkTheme -> DarkColors
        else -> LightColors
    }

    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as Activity).window
            window.statusBarColor = colorScheme.background.toArgb()
            WindowCompat.getInsetsController(window, view).isAppearanceLightStatusBars = !darkTheme
        }
    }

    CompositionLocalProvider(LocalStudioStyle provides studio) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = if (studio) StudioTypography else Typography,
            shapes = if (studio) StudioShapes else androidx.compose.material3.Shapes(),
            content = content
        )
    }
}
